"""Scenario definitions: GeoJSON files in, validated dataclasses out.

A scenario is ONE GeoJSON FeatureCollection in ``config.scenarios.dir``
(README §7 Phase 6: "define a scenario as a GeoJSON"); the file stem is
the scenario's name. It is deliberately a plain data file: anyone can
redraw an alignment or change an assumed speed without touching code.
Features are discriminated by their ``kind`` property:

``line`` (LineString)
    A transit line. ``mode`` must be one of the known transit modes;
    ``speed_kmh`` and ``headway_min`` default to the assumed values in
    ``access.transit``. With ``extends_route_ref`` the line extends every
    existing route of that mode and ``ref`` instead of being a separate
    service — riders stay on the same vehicle, so no second boarding
    wait is charged (speed/headway overrides are forbidden: an extended
    route keeps its own). Stops come from ``stop`` features naming the
    line, or are synthesized every ``stop_spacing_m`` along it.

``stop`` (Point)
    An explicit station of the line named in its ``line`` property.
    Stations are ordered by their position ALONG the drawn line, not by
    feature order, and must lie close to it (a far-away stop is a typo,
    not a station).

``bike_boost`` (LineString)
    A street corridor whose bike edges get a higher flat speed
    (``speed_kmh`` required) — the README's "bike speed boost on
    selected streets". ``buffer_m`` widens or narrows the corridor.

Validation is strict and fails with the file name and feature in the
message: a drawing mistake should die here, not as a silent zero-delta
scenario three steps later.
"""

from __future__ import annotations

import json
import math
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import shapely
from pyproj import Transformer
from shapely.geometry import LineString, Point

from almaty_access.config import Config
from almaty_access.schemas import SCENARIO_FEATURE_KINDS, TRANSIT_MODES

#: A stop farther than this from its line (metres) is a drawing error.
MAX_STOP_OFFSET_M = 200.0

#: Sanity bounds for per-feature speed overrides, km/h.
MAX_TRANSIT_SPEED_KMH = 120.0
MAX_BIKE_SPEED_KMH = 60.0

#: Sanity bound for per-line headway overrides, minutes.
MAX_HEADWAY_MIN = 120.0

#: Scenario names become output file names: keep them path-safe.
_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9_-]*$")

_LINE_KEYS = {
    "kind",
    "name",
    "mode",
    "speed_kmh",
    "headway_min",
    "extends_route_ref",
    "stop_spacing_m",
    "note",
}
_STOP_KEYS = {"kind", "name", "line", "note"}
_BOOST_KEYS = {"kind", "name", "speed_kmh", "buffer_m", "note"}


@dataclass(frozen=True)
class Station:
    """One station of a scenario line, placed along the drawn alignment."""

    name: str
    lon: float
    lat: float
    x: float
    """Metric-CRS coordinates (connectors and distances live here)."""
    y: float
    s_m: float
    """Position along the drawn line, metres from its start."""
    synthesized: bool
    """True when generated by spacing rather than drawn as a point."""


@dataclass(frozen=True)
class TransitLine:
    """A validated ``line`` feature with its stations resolved."""

    name: str
    mode: str
    speed_kmh: float | None
    """Assumed commercial speed; None for an extension, which rides at
    the extended route's own mode speed."""
    headway_min: float | None
    """Assumed headway; None for an extension (the route keeps its own)."""
    extends_route_ref: str | None
    length_m: float
    geometry_m: LineString
    """The drawn alignment in the metric CRS: hop lengths are measured
    along it, and an extension projects the attached terminal onto it."""
    start_xy: tuple[float, float]
    """Metric coordinates of the drawn line's first vertex — an extension
    attaches where one of these ends meets an existing route terminal."""
    end_xy: tuple[float, float]
    stations: tuple[Station, ...]
    """Ordered by position along the line (``s_m`` ascending)."""


@dataclass(frozen=True)
class BikeBoost:
    """A validated ``bike_boost`` feature."""

    name: str
    speed_kmh: float
    buffer_m: float
    geometry_m: LineString
    """The corridor in the metric CRS, for edge matching."""
    length_m: float


@dataclass(frozen=True)
class Scenario:
    """One scenario file, fully validated."""

    name: str
    path: Path
    title: str
    note: str
    sources: tuple[str, ...]
    lines: tuple[TransitLine, ...]
    boosts: tuple[BikeBoost, ...]

    @property
    def modes(self) -> tuple[str, ...]:
        """Top-level travel modes this scenario changes."""
        modes: list[str] = []
        if self.lines:
            modes.append("transit")
        if self.boosts:
            modes.append("bike")
        return tuple(modes)


def load_scenarios(config: Config) -> list[Scenario]:
    """All scenario files in ``config.scenarios.dir``, sorted by name.

    Raises
    ------
    ValueError
        If the directory holds no ``*.geojson`` files, or any file fails
        validation (the message names the file and the feature).
    """
    paths = sorted(config.scenarios.dir.glob("*.geojson"))
    if not paths:
        raise ValueError(
            f"no scenario files: put at least one *.geojson into {config.scenarios.dir} "
            "(README §7 Phase 6) or point 'scenarios.dir' elsewhere"
        )
    scenarios = [load_scenario(path, config) for path in paths]
    names = [scenario.name for scenario in scenarios]
    if len(set(names)) != len(names):
        raise ValueError(f"duplicate scenario names in {config.scenarios.dir}: {names}")
    return scenarios


def load_scenario(path: Path, config: Config) -> Scenario:
    """Parse and validate one scenario GeoJSON file."""
    name = path.stem
    if not _NAME_RE.match(name):
        raise ValueError(
            f"scenario {path.name}: file name must be lowercase [a-z0-9_-] "
            "(it becomes part of output file names)"
        )
    try:
        raw = json.loads(path.read_text(encoding="utf-8-sig"))
    except json.JSONDecodeError as exc:
        raise ValueError(f"scenario {path.name}: not valid JSON: {exc}") from exc
    if not isinstance(raw, dict) or raw.get("type") != "FeatureCollection":
        raise ValueError(f"scenario {path.name}: must be a GeoJSON FeatureCollection")
    features = raw.get("features")
    if not isinstance(features, list) or not features:
        raise ValueError(f"scenario {path.name}: 'features' must be a non-empty list")

    meta = raw.get("properties") or {}
    if not isinstance(meta, dict):
        raise ValueError(f"scenario {path.name}: top-level 'properties' must be a mapping")
    sources = meta.get("sources", [])
    if not isinstance(sources, list) or not all(isinstance(s, str) for s in sources):
        raise ValueError(f"scenario {path.name}: properties.sources must be a list of strings")

    to_metric = Transformer.from_crs(
        config.crs.storage, config.crs.metric, always_xy=True
    ).transform

    lines: list[dict[str, Any]] = []
    stops: list[dict[str, Any]] = []
    boosts: list[BikeBoost] = []
    for index, feature in enumerate(features):
        where = f"scenario {path.name}, feature {index}"
        properties = _feature_properties(feature, where)
        kind = properties.get("kind")
        if kind not in SCENARIO_FEATURE_KINDS:
            raise ValueError(
                f"{where}: 'kind' must be one of {list(SCENARIO_FEATURE_KINDS)}, got {kind!r}"
            )
        where = f"scenario {path.name}, {kind} {properties.get('name', index)!r}"
        if kind == "line":
            lines.append(_parse_line(feature, properties, where, config, to_metric))
        elif kind == "stop":
            stops.append(_parse_stop(feature, properties, where, to_metric))
        else:
            boosts.append(_parse_boost(feature, properties, where, config, to_metric))

    line_names = [line["name"] for line in lines]
    if len(set(line_names)) != len(line_names):
        raise ValueError(f"scenario {path.name}: duplicate line names: {line_names}")
    for stop in stops:
        if stop["line"] not in line_names:
            raise ValueError(
                f"scenario {path.name}, stop {stop['name']!r}: references unknown line "
                f"{stop['line']!r} (lines in this file: {line_names or 'none'})"
            )

    resolved = tuple(
        _resolve_line(line, [s for s in stops if s["line"] == line["name"]], config, path)
        for line in lines
    )
    if not resolved and not boosts:
        raise ValueError(f"scenario {path.name}: contains neither a transit line nor a bike_boost")
    return Scenario(
        name=name,
        path=path,
        title=str(meta.get("title", name)),
        note=str(meta.get("note", "")),
        sources=tuple(sources),
        lines=resolved,
        boosts=tuple(boosts),
    )


def _feature_properties(feature: Any, where: str) -> dict[str, Any]:
    if not isinstance(feature, dict) or feature.get("type") != "Feature":
        raise ValueError(f"{where}: every entry of 'features' must be a GeoJSON Feature")
    properties = feature.get("properties")
    if not isinstance(properties, dict):
        raise ValueError(f"{where}: 'properties' must be a mapping with a 'kind'")
    return properties


def _geometry(feature: dict, expected: str, where: str) -> LineString | Point:
    try:
        geom = shapely.geometry.shape(feature.get("geometry") or {})
    except (ValueError, TypeError, AttributeError, KeyError) as exc:
        raise ValueError(f"{where}: invalid geometry: {exc}") from exc
    if geom.geom_type != expected:
        raise ValueError(f"{where}: geometry must be a {expected}, got {geom.geom_type}")
    if not geom.is_valid or geom.is_empty:
        raise ValueError(f"{where}: geometry is empty or invalid")
    return geom


def _check_keys(properties: dict, allowed: set[str], where: str) -> None:
    unknown = sorted(set(properties) - allowed)
    if unknown:
        raise ValueError(f"{where}: unknown properties {unknown}; allowed: {sorted(allowed)}")


def _required_str(properties: dict, key: str, where: str) -> str:
    value = properties.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{where}: property '{key}' must be a non-empty string")
    return value.strip()


def _optional_number(properties: dict, key: str, where: str, *, upper: float) -> float | None:
    value = properties.get(key)
    if value is None:
        return None
    if (
        not isinstance(value, (int, float))
        or isinstance(value, bool)
        or not math.isfinite(value)
        or not (0 < value <= upper)
    ):
        raise ValueError(f"{where}: property '{key}' must be a number in (0, {upper:g}]")
    return float(value)


def _parse_line(feature: dict, properties: dict, where: str, config: Config, to_metric) -> dict:
    _check_keys(properties, _LINE_KEYS, where)
    name = _required_str(properties, "name", where)
    mode = properties.get("mode")
    if mode not in TRANSIT_MODES:
        raise ValueError(f"{where}: 'mode' must be one of {list(TRANSIT_MODES)}, got {mode!r}")
    extends = properties.get("extends_route_ref")
    if extends is not None:
        extends = _required_str(properties, "extends_route_ref", where)
        for key in ("speed_kmh", "headway_min"):
            if key in properties:
                raise ValueError(
                    f"{where}: '{key}' is not allowed on an extension — an extended "
                    "route keeps its own speed and headway (same trains, same schedule)"
                )
    geometry = _geometry(feature, "LineString", where)
    metric = shapely.transform(geometry, lambda coords: np.column_stack(to_metric(*coords.T)))
    return {
        "name": name,
        "mode": mode,
        "speed_kmh": _optional_number(properties, "speed_kmh", where, upper=MAX_TRANSIT_SPEED_KMH),
        "headway_min": _optional_number(properties, "headway_min", where, upper=MAX_HEADWAY_MIN),
        "extends_route_ref": extends,
        "stop_spacing_m": _optional_number(properties, "stop_spacing_m", where, upper=10_000.0),
        "geometry": geometry,
        "metric": metric,
        "where": where,
    }


def _parse_stop(feature: dict, properties: dict, where: str, to_metric) -> dict:
    _check_keys(properties, _STOP_KEYS, where)
    geometry = _geometry(feature, "Point", where)
    x, y = to_metric(geometry.x, geometry.y)
    return {
        "name": _required_str(properties, "name", where),
        "line": _required_str(properties, "line", where),
        "lon": float(geometry.x),
        "lat": float(geometry.y),
        "x": float(x),
        "y": float(y),
        "where": where,
    }


def _parse_boost(
    feature: dict, properties: dict, where: str, config: Config, to_metric
) -> BikeBoost:
    _check_keys(properties, _BOOST_KEYS, where)
    name = _required_str(properties, "name", where)
    speed = _optional_number(properties, "speed_kmh", where, upper=MAX_BIKE_SPEED_KMH)
    if speed is None:
        raise ValueError(f"{where}: 'speed_kmh' is required on a bike_boost")
    buffer_m = _optional_number(properties, "buffer_m", where, upper=1000.0)
    geometry = _geometry(feature, "LineString", where)
    metric = shapely.transform(geometry, lambda coords: np.column_stack(to_metric(*coords.T)))
    return BikeBoost(
        name=name,
        speed_kmh=speed,
        buffer_m=config.scenarios.bike_buffer_m if buffer_m is None else buffer_m,
        geometry_m=metric,
        length_m=float(metric.length),
    )


def _resolve_line(line: dict, stops: list[dict], config: Config, path: Path) -> TransitLine:
    """Order explicit stops along the line, or synthesize them by spacing."""
    metric: LineString = line["metric"]
    length = float(metric.length)
    where = line["where"]

    stations: list[Station]
    if stops:
        names = [stop["name"] for stop in stops]
        if len(set(names)) != len(names):
            raise ValueError(f"{where}: duplicate stop names {names}")
        stations = []
        for stop in stops:
            point = Point(stop["x"], stop["y"])
            offset = float(metric.distance(point))
            if offset > MAX_STOP_OFFSET_M:
                raise ValueError(
                    f"{stop['where']}: {offset:.0f} m away from line {line['name']!r} "
                    f"(max {MAX_STOP_OFFSET_M:.0f} m) — probably a coordinate typo"
                )
            stations.append(
                Station(
                    name=stop["name"],
                    lon=stop["lon"],
                    lat=stop["lat"],
                    x=stop["x"],
                    y=stop["y"],
                    s_m=float(metric.project(point)),
                    synthesized=False,
                )
            )
        stations.sort(key=lambda station: station.s_m)
        positions = [station.s_m for station in stations]
        if len(positions) != len(set(positions)):
            raise ValueError(f"{where}: two stops project to the same position on the line")
    else:
        spacing = line["stop_spacing_m"] or config.scenarios.stop_spacing_m
        n_stations = max(2, round(length / spacing) + 1)
        to_storage = Transformer.from_crs(
            config.crs.metric, config.crs.storage, always_xy=True
        ).transform
        stations = []
        for i, s_m in enumerate(np.linspace(0.0, length, n_stations)):
            point = metric.interpolate(float(s_m))
            lon, lat = to_storage(point.x, point.y)
            stations.append(
                Station(
                    name=f"{line['name']} {i + 1}",
                    lon=float(lon),
                    lat=float(lat),
                    x=float(point.x),
                    y=float(point.y),
                    s_m=float(s_m),
                    synthesized=True,
                )
            )

    minimum = 1 if line["extends_route_ref"] else 2
    if len(stations) < minimum:
        why = (
            "the extended route provides the other end"
            if minimum == 1
            else "a line is legs between stops"
        )
        raise ValueError(f"{where}: needs at least {minimum} stop(s) ({why})")
    speed = line["speed_kmh"]
    headway = line["headway_min"]
    if line["extends_route_ref"] is None:
        if speed is None:
            speed = config.access.transit.speeds_kmh[line["mode"]]
        if headway is None:
            headway = config.access.transit.headways_min[line["mode"]]
    coords = shapely.get_coordinates(metric)
    return TransitLine(
        name=line["name"],
        mode=line["mode"],
        speed_kmh=speed,
        headway_min=headway,
        extends_route_ref=line["extends_route_ref"],
        length_m=length,
        geometry_m=metric,
        start_xy=(float(coords[0, 0]), float(coords[0, 1])),
        end_xy=(float(coords[-1, 0]), float(coords[-1, 1])),
        stations=tuple(stations),
    )
